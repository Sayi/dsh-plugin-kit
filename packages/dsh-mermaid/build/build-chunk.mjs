/**
 * Bundle `build/mermaid-entry.mjs` into the plugin's lazy client chunk.
 *
 *   node build/build-chunk.mjs
 *
 * The output `client.mermaid.js` follows the loader protocol a package-local chunk
 * uses (the same envelope the shipped Document Preview gives `client.pdf.js`):
 * `window.__ModuleLoader__.load({ id, chunk, factory })`, fetched on demand by
 * `require.async('./client.mermaid.js')`. The chunk is committed, so installing this
 * plugin needs no build step; re-run this script only when Mermaid is upgraded.
 *
 * The chunk must be self-contained: the protocol does not let a chunk require another
 * relative `client*.js` output, and nothing is resolved at run time, so a dynamic
 * `import()` surviving the bundle would fetch a path the Host does not serve. The build
 * fails loudly if one remains.
 */

import { utimes, writeFile } from 'node:fs/promises'
import { build } from 'esbuild'

const PACKAGE = 'dsh-mermaid'
const CHUNK = 'client.mermaid.js'
const HERE = new URL('.', import.meta.url)

const result = await build({
  entryPoints: [new URL('mermaid-entry.mjs', HERE).pathname],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
})

const [output] = result.outputFiles
const body = output.text
if (/\bimport\s*\(/.test(body)) {
  throw new Error('the bundle still contains a dynamic import(); mermaid must inline its diagram chunks')
}
if (!body.includes('renderDiagram')) {
  throw new Error('the bundle does not export renderDiagram')
}

const indent = (text) => text.replace(/^(?=.)/gm, '\t\t')
const chunk = [
  `// ${CHUNK} — generated by build/build-chunk.mjs from build/mermaid-entry.mjs.`,
  '// Mermaid is MIT-licensed; this file is a bundle of it and its dependencies.',
  'window.__ModuleLoader__.load({',
  `\tid: ${JSON.stringify(PACKAGE)},`,
  `\tchunk: ${JSON.stringify(CHUNK)},`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  indent(body),
  '\t\treturn module.exports;',
  '\t}',
  '});',
  '',
].join('\n')

const target = new URL(`../${CHUNK}`, HERE)
await writeFile(target, chunk)

// The Host derives a package's revision from the entry's mtime, ctime and size and
// never scans sibling chunks, so a chunk-only rebuild has to move `client.js`.
const now = new Date()
await utimes(new URL('../client.js', HERE), now, now)

const kib = (chunk.length / 1024).toFixed(0)
console.log(`wrote ${CHUNK} (${kib} KiB), and bumped client.js so the revision follows`)
